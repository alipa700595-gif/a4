  <!-- Section 10: Curated Garment Longevity & Care Protocol -->
  <section class="section-padding bg-white" id="care-protocol">
    <div class="container">
      <div class="section-header">
        <span class="section-subtitle">Wardrobe Stewardship</span>
        <h2>The Garment Longevity &amp; Care Protocol</h2>
        <p>When properly maintained, natural fibers gain character with age. Follow our atelier preservation standards to extend the life of your wardrobe.</p>
      </div>
      <div class="grid-3">
        <div class="editorial-card" style="padding:30px;">
          <h4 style="margin-bottom:12px; color:var(--primary-amber);">1. The Cedar Rest Cycle</h4>
          <p>Never wear a tailored wool coat two days consecutively. Allow 24 hours on a wide-shouldered contoured hanger in a well-ventilated cedar closet to allow fibers to recover their natural spring.</p>
        </div>
        <div class="editorial-card" style="padding:30px;">
          <h4 style="margin-bottom:12px; color:var(--primary-amber);">2. Boar-Bristle Brushing</h4>
          <p>Avoid frequent chemical dry cleaning. Use a natural boar-bristle garment brush downward after each outing to remove surface dust, release trapped moisture, and smooth cashmere pile.</p>
        </div>
        <div class="editorial-card" style="padding:30px;">
          <h4 style="margin-bottom:12px; color:var(--primary-amber);">3. Steam Over Iron</h4>
          <p>High-pressure dry irons crush delicate wool scales and scorch raw silk. Instead, utilize gentle vertical steam to relax creases and naturally deodorize garments without flattening fiber loft.</p>
        </div>
      </div>
    </div>
  </section>

